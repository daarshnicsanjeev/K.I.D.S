import { describe, it, expect, vi } from 'vitest';
import * as vm from 'vm';
import { GasProvisionerService } from '../src/services/gasProvisioner';

describe('Apps Script Syntax Integrity Verification', () => {
  it('guarantees that every .gs file generated by GasProvisionerService has 100% valid JavaScript syntax with zero parse errors', async () => {
    let capturedFiles: Array<{ name: string; type: string; source: string }> = [];

    // Mock fetch to intercept the payload sent to https://script.googleapis.com/v1/projects/.../content
    const originalFetch = globalThis.fetch;
    globalThis.fetch = vi.fn(async (url: any, opts: any) => {
      const urlStr = url.toString();
      if (urlStr.includes('/content')) {
        const parsed = JSON.parse(opts.body);
        capturedFiles = parsed.files;
        return {
          ok: true,
          status: 200,
          json: async () => ({})
        } as any;
      }
      return {
        ok: true,
        status: 200,
        json: async () => ({})
      } as any;
    });

    try {
      // Test with typical configuration
      await GasProvisionerService.updateProjectContent(
        'test_script_id',
        'test_access_key',
        'test_token',
        'Atharva',
        '2026-2027'
      );

      expect(capturedFiles.length).toBeGreaterThan(0);

      const errors: Array<{ file: string; line: number; message: string; snippet: string }> = [];

      for (const file of capturedFiles) {
        if (file.type === 'SERVER_JS') {
          const lines = file.source.split('\n');
          try {
            // Compile code using Node's V8 script compiler
            new vm.Script(file.source, { filename: `${file.name}.gs` });
          } catch (err: any) {
            let errorLine = 1;
            const match = (err.stack || '').match(/\.gs:(\d+)/);
            if (match) {
              errorLine = parseInt(match[1], 10);
            }
            errors.push({
              file: `${file.name}.gs`,
              line: errorLine,
              message: err.message,
              snippet: lines[errorLine - 1] || ''
            });
          }
        } else if (file.name === 'appsscript') {
          // Verify appsscript.json is valid JSON
          expect(() => JSON.parse(file.source)).not.toThrow();
        }
      }

      if (errors.length > 0) {
        const errorDetails = errors
          .map(e => `[${e.file}:${e.line}] ${e.message}\n  Code: "${e.snippet.trim()}"`)
          .join('\n\n');
        throw new Error(`Google Apps Script deployment payload contains ${errors.length} syntax error(s):\n${errorDetails}`);
      }

      expect(errors).toHaveLength(0);
    } finally {
      globalThis.fetch = originalFetch;
    }
  });

  it('guarantees syntax validity even with edge-case child names containing quotes, apostrophes, and hyphens', async () => {
    let capturedFiles: Array<{ name: string; type: string; source: string }> = [];

    const originalFetch = globalThis.fetch;
    globalThis.fetch = vi.fn(async (url: any, opts: any) => {
      const urlStr = url.toString();
      if (urlStr.includes('/content')) {
        const parsed = JSON.parse(opts.body);
        capturedFiles = parsed.files;
        return {
          ok: true,
          status: 200,
          json: async () => ({})
        } as any;
      }
      return {
        ok: true,
        status: 200,
        json: async () => ({})
      } as any;
    });

    try {
      // Child name with quotes and punctuation
      await GasProvisionerService.updateProjectContent(
        'test_script_id',
        'test_access_key',
        'test_token',
        'Mary-Jane "MJ" O\'Connor',
        '2026-2027'
      );

      for (const file of capturedFiles) {
        if (file.type === 'SERVER_JS') {
          expect(() => {
            new vm.Script(file.source, { filename: `${file.name}.gs` });
          }).not.toThrow();
        }
      }
    } finally {
      globalThis.fetch = originalFetch;
    }
  });
});
